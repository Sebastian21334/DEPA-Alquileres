CREATE TABLE IF NOT EXISTS public.estado_disputa (
  id_estado_disputa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE,
  nombre varchar(100) NOT NULL
);

INSERT INTO public.estado_disputa (codigo, nombre) VALUES
  ('ABIERTA', 'Abierta'),
  ('EN_REVISION', 'En revisión'),
  ('GANADA', 'Ganada'),
  ('PERDIDA', 'Perdida'),
  ('CERRADA', 'Cerrada')
ON CONFLICT (codigo) DO NOTHING;

ALTER TABLE public.disputa ADD COLUMN IF NOT EXISTS id_estado_disputa integer;

DO $$
DECLARE
  id_abierta integer;
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'disputa' AND column_name = 'estado'
  ) THEN
    UPDATE public.disputa AS disputa
    SET id_estado_disputa = catalogo.id_estado_disputa
    FROM public.estado_disputa AS catalogo
    WHERE catalogo.codigo = disputa.estado::text;
  END IF;

  ALTER TABLE public.disputa ALTER COLUMN id_estado_disputa SET NOT NULL;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.disputa'::regclass AND conname = 'FK_disputa_estado'
  ) THEN
    ALTER TABLE public.disputa ADD CONSTRAINT "FK_disputa_estado"
      FOREIGN KEY (id_estado_disputa) REFERENCES public.estado_disputa(id_estado_disputa)
      ON DELETE RESTRICT;
  END IF;

  SELECT id_estado_disputa INTO STRICT id_abierta
  FROM public.estado_disputa WHERE codigo = 'ABIERTA';
  EXECUTE format('ALTER TABLE public.disputa ALTER COLUMN id_estado_disputa SET DEFAULT %s', id_abierta);
  ALTER TABLE public.disputa DROP COLUMN IF EXISTS estado;
END $$;

DROP TYPE IF EXISTS public.disputa_estado_enum;
