CREATE TABLE IF NOT EXISTS public.solicitud_cancelacion (
  id_solicitud_cancelacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva integer NOT NULL,
  id_solicitante integer NOT NULL,
  motivo character varying(500) NOT NULL,
  estado public.solicitud_cancelacion_estado_enum NOT NULL DEFAULT 'PENDIENTE',
  id_decidida_por integer,
  decidida_en timestamp without time zone,
  observacion character varying(500),
  creada_en timestamp without time zone NOT NULL DEFAULT now(),
  CONSTRAINT FK_solicitud_cancelacion_reserva FOREIGN KEY (id_reserva)
    REFERENCES public.reserva(id_reserva) ON DELETE CASCADE,
  CONSTRAINT FK_solicitud_cancelacion_solicitante FOREIGN KEY (id_solicitante)
    REFERENCES public.usuario(id_usuario) ON DELETE CASCADE,
  CONSTRAINT FK_solicitud_cancelacion_decidida FOREIGN KEY (id_decidida_por)
    REFERENCES public.usuario(id_usuario) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS IX_solicitud_cancelacion_reserva
  ON public.solicitud_cancelacion(id_reserva);
CREATE UNIQUE INDEX IF NOT EXISTS UX_solicitud_cancelacion_pendiente
  ON public.solicitud_cancelacion(id_reserva)
  WHERE estado = 'PENDIENTE';

CREATE TABLE IF NOT EXISTS public.reembolso (
  id_reembolso integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva integer NOT NULL,
  id_pago integer NOT NULL,
  tipo public.reembolso_tipo_enum NOT NULL,
  origen public.reembolso_origen_enum NOT NULL,
  importe numeric(10,2) NOT NULL,
  moneda character varying(3) NOT NULL DEFAULT 'ARS',
  estado public.reembolso_estado_enum NOT NULL DEFAULT 'PENDIENTE',
  motivo character varying(500) NOT NULL,
  referencia_interna character varying(150),
  referencia_externa character varying(150) UNIQUE,
  id_externo character varying(100) UNIQUE,
  idempotency_key character varying(36) NOT NULL UNIQUE,
  id_solicitado_por integer,
  id_resuelto_por integer,
  creado_en timestamp without time zone NOT NULL DEFAULT now(),
  resuelto_en timestamp without time zone,
  error_detalle character varying(500),
  CONSTRAINT FK_reembolso_reserva FOREIGN KEY (id_reserva)
    REFERENCES public.reserva(id_reserva) ON DELETE CASCADE,
  CONSTRAINT FK_reembolso_pago FOREIGN KEY (id_pago)
    REFERENCES public.pago(id_pago) ON DELETE CASCADE,
  CONSTRAINT FK_reembolso_solicitado FOREIGN KEY (id_solicitado_por)
    REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
  CONSTRAINT FK_reembolso_resuelto FOREIGN KEY (id_resuelto_por)
    REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
  CONSTRAINT CK_reembolso_importe CHECK (importe > 0)
);

CREATE INDEX IF NOT EXISTS IX_reembolso_reserva ON public.reembolso(id_reserva);
CREATE INDEX IF NOT EXISTS IX_reembolso_pago ON public.reembolso(id_pago);

CREATE TABLE IF NOT EXISTS public.disputa (
  id_disputa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva integer NOT NULL,
  id_pago integer NOT NULL,
  origen public.disputa_origen_enum NOT NULL,
  estado public.disputa_estado_enum NOT NULL DEFAULT 'ABIERTA',
  importe numeric(10,2) NOT NULL,
  moneda character varying(3) NOT NULL DEFAULT 'ARS',
  motivo character varying(500),
  chargeback_id character varying(150) UNIQUE,
  referencia_externa character varying(150),
  evidencia jsonb,
  fecha_limite_respuesta timestamp without time zone,
  resolucion character varying(500),
  estado_pago_previo character varying(20),
  estado_liquidacion_previo character varying(40),
  id_resuelto_por integer,
  creado_en timestamp without time zone NOT NULL DEFAULT now(),
  resuelto_en timestamp without time zone,
  CONSTRAINT FK_disputa_reserva FOREIGN KEY (id_reserva)
    REFERENCES public.reserva(id_reserva) ON DELETE CASCADE,
  CONSTRAINT FK_disputa_pago FOREIGN KEY (id_pago)
    REFERENCES public.pago(id_pago) ON DELETE CASCADE,
  CONSTRAINT FK_disputa_resuelto FOREIGN KEY (id_resuelto_por)
    REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
  CONSTRAINT CK_disputa_importe CHECK (importe > 0)
);

CREATE INDEX IF NOT EXISTS IX_disputa_reserva ON public.disputa(id_reserva);
CREATE INDEX IF NOT EXISTS IX_disputa_pago ON public.disputa(id_pago);

