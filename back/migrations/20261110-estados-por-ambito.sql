DO $$
DECLARE
  campo record;
  tipo_actual text;
  tabla_regclass regclass;
  nombre_fk text;
  nombre_check text;
BEGIN
  FOR campo IN
    SELECT * FROM (VALUES
      ('reserva', 'estado_pago', 'ambito_estado_pago', 'PAGO_RESERVA', 'APROBADO'),
      ('reserva', 'estado_liquidacion', 'ambito_estado_liquidacion', 'LIQUIDACION_RESERVA', 'NO_APLICA'),
      ('solicitud_cancelacion', 'estado', 'ambito_estado', 'SOLICITUD_CANCELACION', 'PENDIENTE'),
      ('reembolso', 'estado', 'ambito_estado', 'REEMBOLSO', 'PENDIENTE'),
      ('reclamo_reserva', 'estado', 'ambito_estado', 'RECLAMO', 'ABIERTO'),
      ('solicitud_verificacion', 'estado', 'ambito_estado', 'VERIFICACION_ANUNCIANTE', 'borrador'),
      ('revision_verificacion', 'estado', 'ambito_estado', 'VERIFICACION_ANUNCIANTE', NULL),
      ('disputa', 'estado', 'ambito_estado', 'DISPUTA', 'ABIERTA')
    ) AS campos(tabla, columna, columna_ambito, ambito, valor_por_defecto)
  LOOP
    tabla_regclass := format('public.%I', campo.tabla)::regclass;
    SELECT t.typtype::text INTO tipo_actual
    FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
    WHERE a.attrelid = tabla_regclass AND a.attname = campo.columna AND NOT a.attisdropped;

    IF tipo_actual IS NULL AND campo.tabla = 'reserva' AND campo.columna = 'estado_liquidacion' THEN
      CONTINUE;
    END IF;

    IF tipo_actual = 'e' THEN
      IF campo.tabla = 'solicitud_cancelacion' THEN
        DROP INDEX IF EXISTS public.ux_solicitud_cancelacion_pendiente;
      END IF;
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I DROP DEFAULT', campo.tabla, campo.columna);
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I TYPE varchar(40) USING %I::text',
        campo.tabla, campo.columna, campo.columna);
    ELSIF tipo_actual IS NULL AND campo.tabla = 'disputa' THEN
      ALTER TABLE public.disputa ADD COLUMN estado varchar(40);
    END IF;

    IF campo.tabla = 'disputa' AND EXISTS (
      SELECT 1 FROM pg_catalog.pg_attribute
      WHERE attrelid = tabla_regclass AND attname = 'id_estado_disputa' AND NOT attisdropped
    ) THEN
      UPDATE public.disputa AS disputa
      SET estado = anterior.codigo
      FROM public.estado_disputa AS anterior
      WHERE disputa.id_estado_disputa = anterior.id_estado_disputa;
      ALTER TABLE public.disputa ALTER COLUMN estado SET NOT NULL;
      ALTER TABLE public.disputa DROP COLUMN id_estado_disputa;
    END IF;

    IF (tipo_actual = 'e' OR tipo_actual IS NULL) AND campo.valor_por_defecto IS NOT NULL THEN
      EXECUTE format('ALTER TABLE public.%I ALTER COLUMN %I SET DEFAULT %L',
        campo.tabla, campo.columna, campo.valor_por_defecto);
    END IF;
    EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS %I varchar(40) NOT NULL DEFAULT %L',
      campo.tabla, campo.columna_ambito, campo.ambito);

    nombre_check := format('ck_%s_%s_ambito', campo.tabla, campo.columna);
    IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint
      WHERE conrelid = tabla_regclass AND conname = nombre_check) THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I CHECK (%I = %L)',
        campo.tabla, nombre_check, campo.columna_ambito, campo.ambito);
    END IF;

    nombre_fk := format('fk_%s_%s', campo.tabla, campo.columna);
    IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint
      WHERE conrelid = tabla_regclass AND conname = nombre_fk) THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (%I, %I)
        REFERENCES public.estado(codigo_ambito, codigo) ON DELETE RESTRICT',
        campo.tabla, nombre_fk, campo.columna_ambito, campo.columna);
    END IF;
  END LOOP;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_solicitud_cancelacion_pendiente
  ON public.solicitud_cancelacion(id_reserva)
  WHERE estado = 'PENDIENTE';

