-- Registro auditable de la liquidación de cada reserva.
-- Se aplica después de 20261110-estados-por-ambito.sql, con el backend detenido.
-- Es repetible: crea la tabla y completa una fila por reserva sin duplicarlas.

INSERT INTO public.ambito (codigo, nombre) VALUES
  ('LIQUIDACION_RESERVA', 'Liquidación de reserva')
ON CONFLICT (codigo) DO NOTHING;

INSERT INTO public.estado (codigo_ambito, codigo, nombre) VALUES
  ('LIQUIDACION_RESERVA', 'NO_APLICA', 'No aplica'),
  ('LIQUIDACION_RESERVA', 'RETENIDO', 'Retenido'),
  ('LIQUIDACION_RESERVA', 'PENDIENTE_PAGO_PROPIETARIO', 'Pendiente de pago al propietario'),
  ('LIQUIDACION_RESERVA', 'EN_REVISION', 'En revisión'),
  ('LIQUIDACION_RESERVA', 'PAGADO_PROPIETARIO', 'Pagado al propietario'),
  ('LIQUIDACION_RESERVA', 'DEVUELTO_INQUILINO', 'Devuelto al inquilino'),
  ('LIQUIDACION_RESERVA', 'DEVUELTO_PARCIAL_INQUILINO', 'Devuelto parcialmente al inquilino')
ON CONFLICT (codigo_ambito, codigo) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.liquidacion (
  id_liquidacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva integer NOT NULL,
  estado character varying(40) NOT NULL DEFAULT 'NO_APLICA',
  ambito_estado character varying(40) NOT NULL DEFAULT 'LIQUIDACION_RESERVA',
  importe numeric(10,2),
  moneda character varying(3),
  referencia character varying(150),
  observacion character varying(500),
  id_admin_resolucion integer,
  fecha_resolucion timestamp without time zone,
  fecha_pago_propietario timestamp without time zone,
  creado_en timestamp without time zone NOT NULL DEFAULT now(),
  actualizado_en timestamp without time zone NOT NULL DEFAULT now(),
  CONSTRAINT uq_liquidacion_reserva UNIQUE (id_reserva),
  CONSTRAINT FK_liquidacion_reserva FOREIGN KEY (id_reserva)
    REFERENCES public.reserva(id_reserva) ON DELETE CASCADE,
  CONSTRAINT FK_liquidacion_admin FOREIGN KEY (id_admin_resolucion)
    REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
  CONSTRAINT ck_liquidacion_estado_ambito CHECK (ambito_estado = 'LIQUIDACION_RESERVA'),
  CONSTRAINT fk_liquidacion_estado FOREIGN KEY (ambito_estado, estado)
    REFERENCES public.estado(codigo_ambito, codigo) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS IX_liquidacion_estado
  ON public.liquidacion(estado);

-- Una fila por reserva. El importe solo se copia si la liquidación ya se resolvió;
-- la reserva conserva la caché de compatibilidad que consumen los flujos actuales.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid = 'public.reserva'::regclass
    AND attname = 'estado_liquidacion' AND NOT attisdropped) THEN
    RETURN;
  END IF;

INSERT INTO public.liquidacion (
  id_reserva,
  estado,
  ambito_estado,
  importe,
  moneda,
  referencia,
  observacion,
  fecha_resolucion,
  fecha_pago_propietario,
  creado_en,
  actualizado_en
)
SELECT
  reserva.id_reserva,
  reserva.estado_liquidacion,
  'LIQUIDACION_RESERVA',
  CASE
    WHEN reserva.estado_liquidacion IN (
      'PAGADO_PROPIETARIO',
      'DEVUELTO_INQUILINO',
      'DEVUELTO_PARCIAL_INQUILINO'
    ) THEN reserva.monto_pago
    ELSE NULL
  END,
  'ARS',
  reserva.referencia_liquidacion,
  reserva.observacion_liquidacion,
  reserva.fecha_resolucion_liquidacion,
  CASE
    WHEN reserva.estado_liquidacion = 'PAGADO_PROPIETARIO'
      THEN reserva.fecha_resolucion_liquidacion
    ELSE NULL
  END,
  COALESCE(reserva.fecha_resolucion_liquidacion, now()),
  COALESCE(reserva.fecha_resolucion_liquidacion, now())
FROM public.reserva AS reserva
ON CONFLICT (id_reserva) DO NOTHING;
END $$;
