ALTER TABLE public.reembolso ADD COLUMN IF NOT EXISTS transferencia_manual boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.reembolso_mensaje (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reembolso integer NOT NULL REFERENCES public.reembolso(id_reembolso) ON DELETE CASCADE,
  id_autor integer REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
  autor varchar(205) NOT NULL,
  administracion boolean NOT NULL,
  texto varchar(1000) NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_reembolso_mensaje_conversacion ON public.reembolso_mensaje (id_reembolso, id);

UPDATE public.reembolso r SET transferencia_manual = true
FROM public.pago p
WHERE p.id_pago = r.id_pago AND p.payment_method_id IS DISTINCT FROM 'account_money'
  AND r.estado = 'PENDIENTE' AND r.id_externo IS NULL AND (to_jsonb(r)->>'primer_intento_en') IS NULL
  AND r.origen <> 'CONTRACARGO';

-- Solo recupera rechazos definitivos identificados por la pasarela. Un fallo incierto conserva su conciliación.
WITH rechazos AS (
  SELECT DISTINCT ON (r.id_pago) r.id_reembolso
  FROM public.reembolso r
  JOIN public.pago p ON p.id_pago = r.id_pago
  WHERE r.estado = 'RECHAZADO' AND r.id_externo IS NOT NULL
    AND r.error_detalle = 'Mercado Pago rechazó el reembolso'
    AND r.importe <= p.amount - p.amount_refunded
    AND NOT EXISTS (
      SELECT 1 FROM public.reembolso otro WHERE otro.id_pago = r.id_pago
        AND otro.estado IN ('PENDIENTE', 'EN_PROCESO', 'FALLIDO')
    )
  ORDER BY r.id_pago, r.id_reembolso DESC
)
UPDATE public.reembolso r SET estado = 'PENDIENTE', transferencia_manual = true,
  resuelto_en = NULL, id_resuelto_por = NULL
FROM rechazos WHERE r.id_reembolso = rechazos.id_reembolso;

-- Recupera cobros históricos que quedaron en revisión sin una devolución activa.
INSERT INTO public.reembolso (
  id_reserva, id_pago, tipo, origen, importe, moneda, estado, motivo,
  referencia_interna, idempotency_key, transferencia_manual
)
SELECT r.id_reserva, p.id_pago,
  CASE WHEN p.amount_refunded = 0 THEN 'TOTAL' ELSE 'PARCIAL' END,
  'PAGO_TARDIO', p.amount - p.amount_refunded, p.currency, 'PENDIENTE', l.observacion,
  'tardio:' || p.id_pago, 'tardio:' || p.id_pago,
  p.payment_method_id IS DISTINCT FROM 'account_money'
FROM public.reserva r
JOIN public.liquidacion l ON l.id_reserva = r.id_reserva
JOIN public.pago p ON p.id_reserva = r.id_reserva
WHERE r.cancelada AND r.estado_pago = 'APROBADO' AND l.estado = 'EN_REVISION'
  AND l.observacion ILIKE 'Pago aprobado%requiere%devoluci%'
  AND p.status = 'approved' AND p.amount - p.amount_refunded > 0
  AND NOT EXISTS (
    SELECT 1 FROM public.reembolso x WHERE x.id_pago = p.id_pago
      AND x.estado IN ('PENDIENTE', 'EN_PROCESO', 'FALLIDO')
  )
ON CONFLICT (idempotency_key) DO NOTHING;
